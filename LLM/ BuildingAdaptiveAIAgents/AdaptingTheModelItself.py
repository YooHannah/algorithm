# L5: Adapting the Model Itself
#
# So far you've made agents smarter without ever touching the model's weights.
# First through behavior adaptation (Lesson 2), then through Code Knowledge
# Graphs (Lessons 3-4). In this notebook, you'll go one layer deeper and see
# how to adapt the model itself using fine-tuning, a more expensive, but
# sometimes necessary, tool for agent adaptation.
#
# Here's what you'll do:
# - Get an intuition for LoRA (Low-Rank Adaptation): why we freeze the original
#   model weights and train two small matrices (A and B) on top, instead of
#   retraining the whole network
# - Explore the trade-off between training too few weights (the new behavior
#   never sticks) and too many (catastrophic forgetting) and why ~1% of weights
#   is often the sweet spot
# - Meet the "super polite" Qwen adapter -- a real LoRA fine-tune trained on
#   ~14,000 synthetic polite Q&A pairs and compare its responses side-by-side
#   against the base model
# - Learn how quantization (compressing 32-bit weights down to 4 bits) makes
#   training and storing these adapters dramatically cheaper, the adapter ends
#   up around 150MB versus several GB for the base model
# - Peek behind the scenes at real training stats: about an hour of training
#   time, ~5% of weights updated, on a 600M-parameter model
# - Build a simple router that uses pattern matching to decide, query by query,
#   whether to answer with the base model or hand off to a fine-tuned adapter,
#   a preview of how this works in production
#
# By the end, you'll understand not just how fine-tuning works, but when it's
# the right tool to reach for compared to the other adaptation strategies
# you've already built.

